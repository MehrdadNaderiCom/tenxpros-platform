export function AudioReader({
  slug,
  title,
  resume,
  resumeEndpoint,
  resumeShadowScope,
  resumeEnabled = true,
}: {
  slug: string;
  title?: string;
  resume: AcademyAudioResumeSnapshot;
  resumeEndpoint: string;
  resumeShadowScope: string | null;
  resumeEnabled?: boolean;
}) {
  const {
    registerSectionAudioController,
    setActiveCue,
    setPlaying: setFollowAlongPlaying,
    setSectionCues,
  } = useAcademyFollowAlong();
  const [status, setStatus] = useState<NarrationStatus | null>(null);
  const [statusFailed, setStatusFailed] = useState(false);
  const [voiceId, setVoiceId] = useState<string | null>(null);
  const [rate, setRate] = useState(1);
  const [playing, setPlaying] = useState(false);
  const [currentTime, setCurrentTime] = useState(0);
  const [duration, setDuration] = useState(0);
  const [serverResume, setServerResume] =
    useState<AcademyAudioResumeSnapshot>(resume);
  const [resumeReconciled, setResumeReconciled] =
    useState(!resumeEnabled);
  const audioRef = useRef<HTMLAudioElement | null>(null);
  const trackRef = useRef<HTMLTrackElement | null>(null);
  const followTrackValidatedRef = useRef(false);
  const followCueEnabledRef = useRef(false);
  const selectedSectionPathRef = useRef<string | null>(
    null,
  );
  const pendingSectionCueRef =
    useRef<AcademyFollowAlongCue | null>(null);
  const pendingSectionSeekAssignedRef = useRef(false);
  // Where to resume (as a fraction of duration) after a mid-playback voice swap.
  const pendingSeekFractionRef = useRef<number | null>(null);
  // A durable saved time uses absolute seconds because the resume key binds it
  // to one immutable asset. It is applied only after media metadata is ready.
  const pendingInitialSeekSecondsRef = useRef<number | null>(null);
  const initialResumeHandledRef = useRef(false);
  const allowAudioSaveRef = useRef(false);
  const lastTimedSaveAtRef = useRef(0);
  const lastShadowSaveAtRef = useRef(0);
  const loadedResumeKeyRef = useRef<string | null>(null);
  const appliedMediaReloadRef = useRef(0);
  const mediaRetryTimerRef = useRef<number | null>(null);
  const mediaRetryAttemptRef = useRef(0);
  const mediaRetrySourceKeyRef = useRef<string | null>(null);
  const mediaPlaybackStartedAtRef = useRef<number | null>(null);
  const playAttemptGenerationRef = useRef(0);
  const stopRestartStateRef =
    useRef<StopRestartState>(null);
  const stopRestartStartedAtRef = useRef(0);
  const stopRestartSawPlayingRef = useRef(false);
  const stopRestartPendingZeroRef = useRef(false);
  const statusRequestGenerationRef = useRef(0);
  const statusRequestRef =
    useRef<Promise<NarrationStatus | null> | null>(null);
  const statusAbortRef = useRef<AbortController | null>(null);
  const rateRef = useRef(1);
  const [mediaReload, setMediaReload] = useState(0);
  const [mediaRetryExhausted, setMediaRetryExhausted] =
    useState(false);
  // Real partners persist to the database and keep this local shadow as a
  // refresh-race fallback. Admin preview is deliberately server-read-only, but
  // its account/partner/lesson-scoped shadow should still restore the admin's
  // own playback position in this browser.
  const resumeAvailable =
    resumeEnabled || Boolean(resumeShadowScope);

  const refreshStatus = useCallback(() => {
    if (statusRequestRef.current) {
      return statusRequestRef.current;
    }
    const requestGeneration =
      ++statusRequestGenerationRef.current;
    const controller = new AbortController();
    statusAbortRef.current = controller;
    const timeout = window.setTimeout(() => {
      controller.abort();
    }, 10_000);
    const request = (async () => {
      try {
        const res = await fetch(`/api/partner/academy/audio/${encodeURIComponent(slug)}`, {
          cache: "no-store",
          signal: controller.signal,
        });
        if (!res.ok) throw new Error(String(res.status));
        const body = (await res.json()) as NarrationStatus;
        if (
          requestGeneration !==
          statusRequestGenerationRef.current
        ) {
          return null;
        }
        setStatus(body);
        setStatusFailed(false);
        return body;
      } catch {
        if (
          requestGeneration !==
          statusRequestGenerationRef.current
        ) {
          return null;
        }
        setStatusFailed(true);
        return null;
      } finally {
        window.clearTimeout(timeout);
        if (statusAbortRef.current === controller) {
          statusAbortRef.current = null;
        }
      }
    })();
    statusRequestRef.current = request;
    void request.then(() => {
      if (statusRequestRef.current === request) {
        statusRequestRef.current = null;
      }
    });
    return request;
  }, [slug]);

  useEffect(
    () => () => {
      statusRequestGenerationRef.current += 1;
      statusAbortRef.current?.abort();
      statusAbortRef.current = null;
      statusRequestRef.current = null;
    },
    [slug],
  );

  const saveResume = useAcademyResumeSaver({
    endpoint: resumeEndpoint,
    initialRevision: serverResume.revision,
    enabled: resumeEnabled,
    onSourceInvalidated: () => {
      void refreshStatus();
    },
  });

  // A page refresh can start its server render before the old document's
  // keepalive POST commits. Re-read once after hydration, when that write has
  // had time to settle. The synchronous local shadow below closes the same
  // race even when this request is slow or storage on the server is briefly
  // unavailable.
  useEffect(() => {
    setServerResume(resume);
    if (!resumeEnabled) {
      setResumeReconciled(true);
      return;
    }
    let cancelled = false;
    let controller: AbortController | null = null;
    let requestTimeout: number | null = null;
    setResumeReconciled(false);
    const reconcile = async () => {
      await new Promise<void>((resolve) => {
        window.setTimeout(resolve, 120);
      });
      if (cancelled) return;
      const requestController = new AbortController();
      controller = requestController;
      requestTimeout = window.setTimeout(
        () => requestController.abort(),
        RESUME_RECONCILE_TIMEOUT_MS,
      );
      const sentAt = Date.now();
      try {
        const response = await fetch(resumeEndpoint, {
          credentials: "same-origin",
          cache: "no-store",
          signal: requestController.signal,
        });
        if (response.ok) {
          const body = (await response.json()) as {
            audio?: AcademyAudioResumeSnapshot;
            serverNow?: unknown;
          };
          if (
            !cancelled &&
            body.audio &&
            typeof body.audio.revision === "number"
          ) {
            const receivedAt = Date.now();
            const serverNow =
              typeof body.serverNow === "number" &&
              Number.isSafeInteger(body.serverNow) &&
              body.serverNow >= 0
                ? body.serverNow
                : null;
            const serverUpdatedAt =
              body.audio.updatedAt;
            setServerResume({
              ...body.audio,
              updatedAt:
                serverNow !== null &&
                typeof serverUpdatedAt === "number" &&
                Number.isSafeInteger(serverUpdatedAt) &&
                serverUpdatedAt >= 0
                  ? Math.max(
                      0,
                      Math.round(
                        serverUpdatedAt +
                          (sentAt + receivedAt) / 2 -
                          serverNow,
                      ),
                    )
                  : serverUpdatedAt,
            });
          }
        }
      } catch {
        // The validated local shadow still provides exact same-browser resume.
      } finally {
        if (requestTimeout !== null) {
          window.clearTimeout(requestTimeout);
          requestTimeout = null;
        }
        if (!cancelled) setResumeReconciled(true);
      }
    };
    void reconcile();
    return () => {
      cancelled = true;
      controller?.abort();
      if (requestTimeout !== null) {
        window.clearTimeout(requestTimeout);
      }
    };
  }, [resume, resumeEnabled, resumeEndpoint]);

  // Initial status, restore saved preferences.
  useEffect(() => {
    try {
      const savedRate = Number(window.localStorage.getItem(RATE_PREF_KEY));
      if (RATES.includes(savedRate)) {
        setRate(savedRate);
        rateRef.current = savedRate;
      }
    } catch {
      /* storage unavailable */
    }
    void refreshStatus();
  }, [refreshStatus]);

  // The first active-release visit safely migrates legacy preferences. The
  // marker is written even when the old speed was not 1.5x, so a user may
  // deliberately choose 1.5x later without it being reset on the next visit.
  useEffect(() => {
    if (!status?.productionVoiceLocked) return;
    const activeVoiceId =
      status.defaultVoice ??
      status.voices.find((voice) => voice.ready)?.id;
    if (!activeVoiceId) return;
    setVoiceId(activeVoiceId);
    try {
      window.localStorage.setItem(
        VOICE_PREF_KEY,
        activeVoiceId,
      );
      if (
        !window.localStorage.getItem(
          ACTIVE_RELEASE_PREF_MIGRATION_KEY,
        )
      ) {
        if (
          Number(
            window.localStorage.getItem(
              RATE_PREF_KEY,
            ),
          ) === 1.5
        ) {
          window.localStorage.setItem(RATE_PREF_KEY, "1");
          setRate(1);
          rateRef.current = 1;
          if (audioRef.current) {
            audioRef.current.playbackRate = 1;
          }
        }
        window.localStorage.setItem(
          ACTIVE_RELEASE_PREF_MIGRATION_KEY,
          status.activeRelease?.id ?? "active",
        );
      }
    } catch {
      /* storage unavailable */
    }
  }, [
    status?.productionVoiceLocked,
    status?.defaultVoice,
    status?.voices,
    status?.activeRelease?.id,
  ]);

  // Pick the voice once the status is known: saved preference if ready,
  // otherwise the configured default, otherwise the first ready voice.
  useEffect(() => {
    if (!status || voiceId) return;
    let saved: string | null = null;
    try {
      saved = window.localStorage.getItem(VOICE_PREF_KEY);
    } catch {
      /* storage unavailable */
    }
    const ready = status.voices.filter((v) => v.ready);
    const pick =
      ready.find((v) => v.id === saved)?.id ??
      ready.find((v) => v.id === status.defaultVoice)?.id ??
      ready[0]?.id ??
      status.defaultVoice;
    if (pick) setVoiceId(pick);
  }, [status, voiceId]);

  // Poll whenever the read-only status reports missing/stale narration. This
  // never starts generation; it only lets a newly activated audited asset
  // replace the temporary device fallback without requiring a page reload.
  const selected = useMemo(
    () => status?.voices.find((v) => v.id === voiceId) ?? null,
    [status, voiceId],
  );
  const followAlong =
    status?.followAlong &&
    selected?.resumeKey === status.followAlong.resumeKey
      ? status.followAlong
      : null;
  const resumePending =
    resumeEnabled && !resumeReconciled;

  const syncActiveTrackCue = useCallback(() => {
    if (
      !followTrackValidatedRef.current ||
      !followCueEnabledRef.current
    ) {
      setActiveCue(null);
      return;
    }
    if (
      pendingSectionCueRef.current &&
      pendingInitialSeekSecondsRef.current !== null
    ) {
      setActiveCue(pendingSectionCueRef.current);
      return;
    }
    const track = trackRef.current?.track;
    if (!track) return;
    let cue: TextTrackCue | null = null;
    // Treat media currentTime and the audited loaded cue list as authoritative.
    // WebKit can briefly retain a non-empty but stale activeCues list after a
    // paused seek, which would otherwise highlight the previous passage.
    if (track.cues && audioRef.current) {
      const time = audioRef.current.currentTime;
      for (
        let index = 0;
        index < track.cues.length;
        index += 1
      ) {
        const candidate = track.cues[index];
        if (
          candidate.startTime <= time &&
          time < candidate.endTime
        ) {
          cue = candidate;
          break;
        }
      }
    } else if (
      track.activeCues &&
      track.activeCues.length > 0
    ) {
      cue = track.activeCues[0];
    }
    const parsedCue = parseFollowAlongCue(cue);
    const audio = audioRef.current;
    if (
      parsedCue &&
      selectedSectionPathRef.current &&
      audio &&
      !audio.paused
    ) {
      selectedSectionPathRef.current =
        academyFollowAlongElementPath(
          parsedCue.sourceHtmlPath,
        );
    }
    setActiveCue(parsedCue);
  }, [setActiveCue]);

  useEffect(() => {
    followTrackValidatedRef.current = false;
    if (
      !followAlong ||
      mediaRetryExhausted ||
      resumePending
    ) {
      selectedSectionPathRef.current = null;
      pendingSectionCueRef.current = null;
      pendingSectionSeekAssignedRef.current = false;
      setFollowAlongPlaying(false);
      setActiveCue(null);
      setSectionCues([]);
      return;
    }
    const element = trackRef.current;
    if (!element) return;
    const track = element.track;
    track.mode = "hidden";
    const onCueChange = () => syncActiveTrackCue();
    const clearTrack = () => {
      followTrackValidatedRef.current = false;
      selectedSectionPathRef.current = null;
      pendingSectionCueRef.current = null;
      pendingSectionSeekAssignedRef.current = false;
      setActiveCue(null);
      setSectionCues([]);
    };
    const onTrackLoad = () => {
      const cues = track.cues;
      if (
        element.readyState !== 2 ||
        !cues ||
        cues.length !== followAlong.cueCount
      ) {
        clearTrack();
        return;
      }
      const sectionCueByPath = new Map<
        string,
        AcademyFollowAlongCue
      >();
      let previousEndMs = -1;
      const durationLimitMs =
        selected?.durationSeconds &&
        Number.isFinite(selected.durationSeconds) &&
        selected.durationSeconds > 0
          ? Math.ceil(
              selected.durationSeconds * 1_000,
            ) + 250
          : MAX_NARRATION_DURATION_MS;
      for (let index = 0; index < cues.length; index += 1) {
        const parsed = parseFollowAlongCue(cues[index]);
        if (
          !parsed ||
          parsed.blockIndex !== index ||
          parsed.startMs < previousEndMs ||
          parsed.endMs > durationLimitMs
        ) {
          clearTrack();
          return;
        }
        previousEndMs = parsed.endMs;
        const sectionPath =
          academyFollowAlongElementPath(
            parsed.sourceHtmlPath,
          );
        const current =
          sectionCueByPath.get(sectionPath);
        if (!current || parsed.startMs < current.startMs) {
          sectionCueByPath.set(sectionPath, parsed);
        }
      }
      followTrackValidatedRef.current = true;
      setSectionCues(
        Array.from(sectionCueByPath.values()).sort(
          (left, right) => left.startMs - right.startMs,
        ),
      );
      syncActiveTrackCue();
    };
    track.addEventListener("cuechange", onCueChange);
    element.addEventListener("load", onTrackLoad);
    element.addEventListener("error", clearTrack);
    if (element.readyState === 2) {
      onTrackLoad();
    }
    return () => {
      track.removeEventListener("cuechange", onCueChange);
      element.removeEventListener("load", onTrackLoad);
      element.removeEventListener("error", clearTrack);
      clearTrack();
    };
  }, [
    followAlong,
    mediaRetryExhausted,
    resumePending,
    selected?.durationSeconds,
    setActiveCue,
    setFollowAlongPlaying,
    setSectionCues,
    syncActiveTrackCue,
  ]);

  useEffect(
    () => () => {
      selectedSectionPathRef.current = null;
      pendingSectionCueRef.current = null;
      pendingSectionSeekAssignedRef.current = false;
      setFollowAlongPlaying(false);
      setActiveCue(null);
      setSectionCues([]);
    },
    [
      setActiveCue,
      setFollowAlongPlaying,
      setSectionCues,
    ],
  );
  useEffect(() => {
    const sourceKey = selected?.resumeKey ?? null;
    if (
      !sourceKey ||
      mediaRetrySourceKeyRef.current === sourceKey
    ) {
      return;
    }
    mediaRetrySourceKeyRef.current = sourceKey;
    mediaRetryAttemptRef.current = 0;
    mediaPlaybackStartedAtRef.current = null;
    setMediaRetryExhausted(false);
    if (mediaRetryTimerRef.current !== null) {
      window.clearTimeout(mediaRetryTimerRef.current);
      mediaRetryTimerRef.current = null;
    }
  }, [selected?.resumeKey]);
  const anyNotReady = Boolean(status?.voices.some((v) => !v.ready));
  useEffect(() => {
    if (
      !status ||
      (status.narration &&
        status.voices.length > 0 &&
        !anyNotReady)
    ) {
      return;
    }
    const id = window.setInterval(() => {
      void refreshStatus();
    }, 5000);
    return () => window.clearInterval(id);
  }, [
    status,
    status?.narration,
    status?.voices.length,
    anyNotReady,
    refreshStatus,
  ]);

  // A failed status fetch must never be terminal: keep retrying quietly so a
  // transient blip or server restart cannot lock the session into the device
  // voice fallback.
  useEffect(() => {
    if (!statusFailed) return;
    const id = window.setInterval(() => {
      void refreshStatus();
    }, 10000);
    return () => window.clearInterval(id);
  }, [statusFailed, refreshStatus]);

  // Engagement telemetry: one event per second of actual playback, the same
  // event the beacon already aggregates.
  useEffect(() => {
    if (!playing) return;
    const id = window.setInterval(() => {
      window.dispatchEvent(new CustomEvent(AUDIO_SECOND_EVENT));
    }, 1000);
    return () => window.clearInterval(id);
  }, [playing]);

  const srcFor = useCallback(
    (v: string) => `/api/partner/academy/audio/${encodeURIComponent(slug)}/${encodeURIComponent(v)}`,
    [slug],
  );

  // The audio element's src is set IMPERATIVELY, never as a React prop: a
  // controlled src prop would be re-committed after changeVoice's in-gesture
  // swap, re-running the media load algorithm and aborting the just-issued
  // play(). This effect only covers mount and the ready transition; it
  // compares the attribute first so it never disturbs an element changeVoice
  // has already pointed at the right source. The immutable resume key is also
  // part of the identity: a new release commonly keeps the same voice and URL.
  useEffect(() => {
    const el = audioRef.current;
    if (
      mediaRetryExhausted ||
      !el ||
      !selected?.ready
    ) {
      return;
    }
    const want = srcFor(selected.id);
    const sourceChanged =
      loadedResumeKeyRef.current !== null &&
      loadedResumeKeyRef.current !== selected.resumeKey;
    if (
      el.getAttribute("src") !== want ||
      loadedResumeKeyRef.current !== selected.resumeKey ||
      appliedMediaReloadRef.current !== mediaReload
    ) {
      selectedSectionPathRef.current = null;
      pendingSectionCueRef.current = null;
      pendingSectionSeekAssignedRef.current = false;
      stopRestartStateRef.current = null;
      stopRestartSawPlayingRef.current = false;
      stopRestartPendingZeroRef.current = false;
      playAttemptGenerationRef.current += 1;
      allowAudioSaveRef.current = false;
      // A retry of the same immutable source keeps the in-memory timestamp.
      // A genuinely new release must never inherit the old asset's position.
      if (sourceChanged) {
        pendingInitialSeekSecondsRef.current = null;
        followCueEnabledRef.current = false;
        setActiveCue(null);
      }
      pendingSeekFractionRef.current = null;
      setPlaying(false);
      setCurrentTime(0);
      setDuration(0);
      loadedResumeKeyRef.current = selected.resumeKey;
      appliedMediaReloadRef.current = mediaReload;
      el.setAttribute("src", want);
      el.load();
    }
  }, [
    selected?.ready,
    selected?.id,
    selected?.resumeKey,
    mediaReload,
    mediaRetryExhausted,
    setActiveCue,
    srcFor,
  ]);

  useEffect(
    () => () => {
      if (mediaRetryTimerRef.current !== null) {
        window.clearTimeout(mediaRetryTimerRef.current);
      }
    },
    [],
  );

  const currentAudioPosition = useCallback(
    (
      requestedTime?: number,
    ): AcademyAudioResumePosition | null => {
      const el = audioRef.current;
      const pendingCheckpoint =
        pendingInitialSeekSecondsRef.current;
      if (
        !resumeAvailable ||
        (!allowAudioSaveRef.current &&
          pendingCheckpoint === null) ||
        !el ||
        !selected?.ready ||
        !selected.resumeKey ||
        loadedResumeKeyRef.current !== selected.resumeKey
      ) {
        return null;
      }
      const authoritativeDuration =
        selected.durationSeconds &&
        Number.isFinite(selected.durationSeconds)
          ? selected.durationSeconds
          : el.duration;
      if (
        !Number.isFinite(authoritativeDuration) ||
        authoritativeDuration <= 0
      ) {
        return null;
      }
      // Media implementations may emit a zero-valued timeupdate while a
      // restored timestamp is still waiting for metadata/canplay. Until that
      // pending seek has actually succeeded, preserve the restored checkpoint
      // instead of letting the transient media time overwrite the shadow with
      // zero during a refresh.
      const checkpointTime =
        stopRestartStateRef.current !== null
          ? 0
          : !allowAudioSaveRef.current &&
              pendingCheckpoint !== null
          ? pendingCheckpoint
          : Number.isFinite(requestedTime)
            ? requestedTime!
            : pendingCheckpoint ?? el.currentTime;
      return {
        kind: "audio",
        resumeKey: selected.resumeKey,
        voiceId: selected.id,
        positionSeconds: Math.min(
          authoritativeDuration,
          Math.max(0, checkpointTime),
        ),
        durationSeconds: authoritativeDuration,
      };
    },
    [
      resumeAvailable,
      selected?.durationSeconds,
      selected?.id,
      selected?.ready,
      selected?.resumeKey,
    ],
  );

  const persistAudioShadow = useCallback(
    (requestedTime?: number) => {
      if (!resumeShadowScope) return;
      const position = currentAudioPosition(requestedTime);
      if (!position) return;
      writeAcademyAudioResumeShadow(resumeShadowScope, {
        resumeKey: position.resumeKey,
        positionSeconds: position.positionSeconds,
        durationSeconds: position.durationSeconds,
        updatedAt: Date.now(),
      });
    },
    [currentAudioPosition, resumeShadowScope],
  );

  const persistAudioPosition = useCallback(
    (
      requestedTime?: number,
      options?: { keepalive?: boolean },
    ) => {
      const position = currentAudioPosition(requestedTime);
      if (!position) return;
      if (resumeShadowScope) {
        writeAcademyAudioResumeShadow(resumeShadowScope, {
          resumeKey: position.resumeKey,
          positionSeconds: position.positionSeconds,
          durationSeconds: position.durationSeconds,
          updatedAt: Date.now(),
        });
      }
      saveResume(position, options);
    },
    [
      currentAudioPosition,
      resumeShadowScope,
      saveResume,
    ],
  );

  const onLoadedMetadata = () => {
    const el = audioRef.current;
    if (!el) return;
    const mediaDuration =
      Number.isFinite(el.duration) && el.duration > 0
        ? el.duration
        : selected?.durationSeconds ?? 0;
    setDuration(mediaDuration);
    const saved =
      pendingInitialSeekSecondsRef.current;
    if (saved != null && mediaDuration > 0) {
      // Show the saved timestamp as soon as metadata is known. The actual seek
      // waits for canplay (or the user's Play gesture) because older iOS
      // versions can ignore currentTime assignments at loadedmetadata.
      setCurrentTime(
        Math.min(
          Math.max(0, saved),
          Math.max(0, mediaDuration - 0.1),
        ),
      );
    } else if (initialResumeHandledRef.current) {
      // A fresh source with no pending bookmark becomes writable only after its
      // authoritative metadata is available.
      allowAudioSaveRef.current = true;
    }
    el.playbackRate = rateRef.current;
    // Keep the voice's pitch natural at non-1x speeds (Safari needs the
    // webkit-prefixed property below iOS 17.2).
    try {
      el.preservesPitch = true;
      (el as HTMLAudioElement & { webkitPreservesPitch?: boolean }).webkitPreservesPitch = true;
    } catch {
      /* cosmetic */
    }
    if (title && "mediaSession" in navigator) {
      try {
        navigator.mediaSession.metadata = new MediaMetadata({ title, artist: "TenXPros Partner Academy" });
      } catch {
        /* metadata is cosmetic */
      }
    }
  };

  // Apply a pending absolute position once the source can actually seek.
  // Restores and passage selections share this confirmation path because iOS
  // can ignore currentTime at loadedmetadata and WebKit can briefly echo a
  // requested clock before its asynchronous seek has settled.
  const applyPendingSeek = useCallback(() => {
    const el = audioRef.current;
    if (!el) return;
    const initialSeconds =
      pendingInitialSeekSecondsRef.current;
    const mediaDuration =
      Number.isFinite(el.duration) && el.duration > 0
        ? el.duration
        : selected?.durationSeconds ?? 0;
    if (
      initialSeconds != null &&
      mediaDuration > 0 &&
      el.readyState >= HTMLMediaElement.HAVE_METADATA
    ) {
      const target = Math.min(
        Math.max(0, initialSeconds),
        Math.max(0, mediaDuration - 0.1),
      );
      const sectionSeekPending =
        pendingSectionCueRef.current !== null;
      const tolerance = sectionSeekPending
        ? 0.075
        : 0.5;
      // A matching, non-seeking media clock is the confirmation. Merely reading
      // the assigned value back is not enough: WebKit can echo the target while
      // its asynchronous seek is still pending and later emit the old clock.
      if (
        (sectionSeekPending &&
          !pendingSectionSeekAssignedRef.current) ||
        Math.abs(el.currentTime - target) > tolerance ||
        el.seeking
      ) {
        if (!el.seeking) {
          try {
            el.currentTime = target;
            if (sectionSeekPending) {
              pendingSectionSeekAssignedRef.current = true;
            }
          } catch {
            // Keep the pending value. canplay/playing will retry when the media
            // implementation is ready to accept a seek.
            return;
          }
        }
        // Keep both the durable checkpoint and the visible clock authoritative
        // until seeked (or a later non-seeking event) confirms the target.
        setCurrentTime(target);
        return;
      }
      pendingInitialSeekSecondsRef.current = null;
      el.playbackRate = rateRef.current;
      setCurrentTime(target);
      allowAudioSaveRef.current = true;
      const selectedSectionCue =
        pendingSectionCueRef.current;
      pendingSectionCueRef.current = null;
      pendingSectionSeekAssignedRef.current = false;
      if (selectedSectionCue) {
        setActiveCue(selectedSectionCue);
      }
      window.requestAnimationFrame(syncActiveTrackCue);
      return;
    }
    const fraction = pendingSeekFractionRef.current;
    if (fraction == null || mediaDuration <= 0) return;
    pendingSeekFractionRef.current = null;
    el.currentTime = Math.max(0.1, fraction * mediaDuration);
    el.playbackRate = rateRef.current;
    followCueEnabledRef.current = true;
    window.requestAnimationFrame(syncActiveTrackCue);
  }, [
    selected?.durationSeconds,
    setActiveCue,
    syncActiveTrackCue,
  ]);

  const requestPlayback = useCallback(
    (el: HTMLAudioElement) => {
      const generation =
        ++playAttemptGenerationRef.current;
      void el.play().catch((error: unknown) => {
        if (
          generation !==
          playAttemptGenerationRef.current
        ) {
          return;
        }
        const errorName =
          typeof error === "object" &&
          error !== null &&
          "name" in error &&
          typeof (error as { name?: unknown }).name ===
            "string"
            ? (error as { name: string }).name
            : "";
        if (errorName === "AbortError") return;
        setPlaying(false);
        setFollowAlongPlaying(false);
        mediaPlaybackStartedAtRef.current = null;
        // Permission denial is local to the gesture. Decode/network failures
        // may mean the audited source changed and deserve a status refresh.
        if (errorName !== "NotAllowedError") {
          void refreshStatus();
        }
      });
    },
    [refreshStatus, setFollowAlongPlaying],
  );

  const rejectStaleStoppedClock = useCallback(
    (el: HTMLAudioElement): boolean => {
      const state = stopRestartStateRef.current;
      if (state === null) return false;

      const mediaTime = el.currentTime;
      if (state === "stopped") {
        if (
          !Number.isFinite(mediaTime) ||
          mediaTime < 0 ||
          mediaTime > 0.01
        ) {
          try {
            el.currentTime = 0;
          } catch {
            /* the visible and persisted Stop state stays at zero */
          }
        }
        setCurrentTime(0);
        return true;
      }
      if (state === "correcting") {
        setCurrentTime(0);
        return true;
      }

      const elapsedSeconds = Math.max(
        0,
        (window.performance.now() -
          stopRestartStartedAtRef.current) /
          1_000,
      );
      const furthestPlausibleTime =
        stopRestartSawPlayingRef.current
          ? Math.max(
              STOP_RESTART_MAX_POSITION_SECONDS,
              elapsedSeconds *
                Math.max(0.25, el.playbackRate) +
                0.5,
            )
          : STOP_RESTART_MAX_POSITION_SECONDS;
      if (
        !Number.isFinite(mediaTime) ||
        mediaTime < 0 ||
        mediaTime > furthestPlausibleTime
      ) {
        // A queued event from before Stop can arrive inside the next play event
        // on WebKit. Retire that obsolete attempt, then retry zero and playback
        // after the injected getter has gone away.
        stopRestartStateRef.current = "correcting";
        stopRestartPendingZeroRef.current = true;
        playAttemptGenerationRef.current += 1;
        el.pause();
        try {
          el.currentTime = 0;
        } catch {
          /* seeked will retry after a stale getter is removed */
        }
        setCurrentTime(0);
        return true;
      }

      // Keep the wall-clock guard for a short window after `playing`. A zero
      // timeupdate can precede the queued stale event on WebKit, so one early
      // plausible tick is not enough to retire Stop's authority.
      if (
        stopRestartSawPlayingRef.current &&
        elapsedSeconds >= 1
      ) {
        stopRestartStateRef.current = null;
        stopRestartSawPlayingRef.current = false;
        stopRestartPendingZeroRef.current = false;
      }
      return false;
    },
    [],
  );

  // Bind the persisted timestamp to the exact immutable audio identity before
  // seeking. A release change simply starts at zero; narration never autoplays.
  useEffect(() => {
    if (
      initialResumeHandledRef.current ||
      !selected?.ready ||
      !resumeReconciled
    ) {
      return;
    }
    initialResumeHandledRef.current = true;
    const shadow = resumeShadowScope
      ? readAcademyAudioResumeShadow(resumeShadowScope)
      : null;
    const selectedResume =
      selectFreshestAcademyAudioResume({
        activeResumeKey: selected.resumeKey,
        server: serverResume,
        shadow,
      });
    const saved =
      selectedResume?.checkpoint.positionSeconds ?? null;
    if (
      resumeAvailable &&
      saved != null &&
      Number.isFinite(saved) &&
      saved > 0
    ) {
      pendingInitialSeekSecondsRef.current = saved;
      followCueEnabledRef.current = true;
      const el = audioRef.current;
      if (
        el &&
        el.readyState >=
          HTMLMediaElement.HAVE_METADATA
      ) {
        applyPendingSeek();
      } else {
        setCurrentTime(saved);
      }
    } else {
      followCueEnabledRef.current = false;
      setActiveCue(null);
      if (
        resumeShadowScope &&
        shadow &&
        shadow.resumeKey !== selected.resumeKey
      ) {
        clearAcademyAudioResumeShadow(resumeShadowScope);
      }
      allowAudioSaveRef.current = true;
    }
  }, [
    applyPendingSeek,
    resumeAvailable,
    resumeReconciled,
    resumeShadowScope,
    serverResume,
    setActiveCue,
    selected?.ready,
    selected?.resumeKey,
  ]);

  const toggle = () => {
    const el = audioRef.current;
    if (!el || resumePending) return;
    if (el.paused) {
      if (stopRestartStateRef.current !== null) {
        stopRestartStateRef.current = "restarting";
        stopRestartStartedAtRef.current =
          window.performance.now();
        stopRestartSawPlayingRef.current = false;
        stopRestartPendingZeroRef.current = false;
      }
      applyPendingSeek();
      if (pendingInitialSeekSecondsRef.current === null) {
        followCueEnabledRef.current = true;
      }
      el.playbackRate = rateRef.current;
      requestPlayback(el);
    } else {
      stopRestartStateRef.current = null;
      stopRestartSawPlayingRef.current = false;
      stopRestartPendingZeroRef.current = false;
      playAttemptGenerationRef.current += 1;
      el.pause();
    }
  };

  const stop = () => {
    const el = audioRef.current;
    if (!el || resumePending) return;
    selectedSectionPathRef.current = null;
    pendingSectionCueRef.current = null;
    pendingSectionSeekAssignedRef.current = false;
    stopRestartStateRef.current = "stopped";
    stopRestartStartedAtRef.current = 0;
    stopRestartSawPlayingRef.current = false;
    stopRestartPendingZeroRef.current = false;
    playAttemptGenerationRef.current += 1;
    followCueEnabledRef.current = false;
    pendingSeekFractionRef.current = null;
    pendingInitialSeekSecondsRef.current = null;
    allowAudioSaveRef.current = true;
    el.pause();
    try {
      el.currentTime = 0;
    } catch {
      // Persisted and visible state remain authoritatively zero.
    }
    setCurrentTime(0);
    setPlaying(false);
    setFollowAlongPlaying(false);
    setActiveCue(null);
    mediaPlaybackStartedAtRef.current = null;
    persistAudioPosition(0);
  };

  const retryStudioAudio = () => {
    mediaRetryAttemptRef.current = 0;
    mediaPlaybackStartedAtRef.current = null;
    setMediaRetryExhausted(false);
    setMediaReload((value) => value + 1);
    void refreshStatus();
  };

  const changeRate = (r: number) => {
    setRate(r);
    rateRef.current = r;
    try {
      window.localStorage.setItem(RATE_PREF_KEY, String(r));
    } catch {
      /* storage unavailable */
    }
    const el = audioRef.current;
    if (el) el.playbackRate = r;
  };

  /**
   * Swap the voice, keeping the position and the playing state. Everything
   * happens synchronously inside the change gesture: set the new source,
   * load, and call play() immediately (it resolves when data arrives), which
   * preserves the playback permission on iOS.
   */
  const changeVoice = (id: string) => {
    selectedSectionPathRef.current = null;
    pendingSectionCueRef.current = null;
    pendingSectionSeekAssignedRef.current = false;
    stopRestartStateRef.current = null;
    stopRestartSawPlayingRef.current = false;
    stopRestartPendingZeroRef.current = false;
    playAttemptGenerationRef.current += 1;
    setVoiceId(id);
    try {
      window.localStorage.setItem(VOICE_PREF_KEY, id);
    } catch {
      /* storage unavailable */
    }
    const el = audioRef.current;
    const target = status?.voices.find((v) => v.id === id);
    if (!el || !target?.ready) return;
    const wasPlaying = !el.paused && !el.ended;
    pendingSeekFractionRef.current =
      Number.isFinite(el.duration) && el.duration > 0 ? el.currentTime / el.duration : null;
    loadedResumeKeyRef.current = target.resumeKey;
    el.src = srcFor(id);
    el.load();
    if (wasPlaying) {
      requestPlayback(el);
    }
  };

  const seek = (t: number) => {
    const el = audioRef.current;
    if (!el || resumePending) return;
    selectedSectionPathRef.current = null;
    pendingSectionCueRef.current = null;
    pendingSectionSeekAssignedRef.current = false;
    stopRestartStateRef.current = null;
    stopRestartSawPlayingRef.current = false;
    stopRestartPendingZeroRef.current = false;
    // A manual seek supersedes any pending voice-swap resume position.
    pendingSeekFractionRef.current = null;
    pendingInitialSeekSecondsRef.current = null;
    allowAudioSaveRef.current = true;
    el.currentTime = t;
    setCurrentTime(t);
    followCueEnabledRef.current = t > 0;
    window.requestAnimationFrame(syncActiveTrackCue);
    persistAudioShadow(t);
  };

  const activateSectionAudio = useCallback(
    (cue: AcademyFollowAlongCue) => {
      const el = audioRef.current;
      if (
        !el ||
        resumePending ||
        !selected?.ready ||
        loadedResumeKeyRef.current !==
          selected.resumeKey ||
        !followTrackValidatedRef.current
      ) {
        return;
      }
      stopRestartStateRef.current = null;
      stopRestartSawPlayingRef.current = false;
      stopRestartPendingZeroRef.current = false;

      const sectionPath = academyFollowAlongElementPath(
        cue.sourceHtmlPath,
      );
      if (
        selectedSectionPathRef.current === sectionPath
      ) {
        if (el.paused) {
          applyPendingSeek();
          followCueEnabledRef.current = true;
          el.playbackRate = rateRef.current;
          requestPlayback(el);
        } else {
          playAttemptGenerationRef.current += 1;
          el.pause();
        }
        return;
      }

      selectedSectionPathRef.current = sectionPath;
      initialResumeHandledRef.current = true;
      pendingSeekFractionRef.current = null;
      followCueEnabledRef.current = true;

      const knownDuration =
        Number.isFinite(el.duration) && el.duration > 0
          ? el.duration
          : selected.durationSeconds;
      const requestedTime = cue.startMs / 1_000;
      const target =
        knownDuration &&
        Number.isFinite(knownDuration) &&
        knownDuration > 0
          ? Math.min(
              requestedTime,
              Math.max(0, knownDuration - 0.1),
            )
          : requestedTime;

      pendingInitialSeekSecondsRef.current = target;
      pendingSectionCueRef.current = cue;
      pendingSectionSeekAssignedRef.current = false;
      allowAudioSaveRef.current = false;
      playAttemptGenerationRef.current += 1;
      el.pause();
      setCurrentTime(target);
      setPlaying(false);
      setFollowAlongPlaying(false);
      setActiveCue(cue);
      mediaPlaybackStartedAtRef.current = null;
      applyPendingSeek();
      persistAudioPosition(target);
    },
    [
      applyPendingSeek,
      persistAudioPosition,
      requestPlayback,
      resumePending,
      selected?.durationSeconds,
      selected?.ready,
      selected?.resumeKey,
      setActiveCue,
      setFollowAlongPlaying,
    ],
  );

  useLayoutEffect(
    () =>
      registerSectionAudioController(
        activateSectionAudio,
      ),
    [
      activateSectionAudio,
      registerSectionAudioController,
    ],
  );

  useEffect(() => {
    if (!resumeAvailable) return;
    const flush = () => {
      persistAudioPosition(undefined, {
        keepalive: true,
      });
    };
    const onVisibility = () => {
      if (document.visibilityState === "hidden") flush();
    };
    window.addEventListener("pagehide", flush);
    document.addEventListener(
      "visibilitychange",
      onVisibility,
    );
    return () => {
      window.removeEventListener("pagehide", flush);
      document.removeEventListener(
        "visibilitychange",
        onVisibility,
      );
    };
  }, [persistAudioPosition, resumeAvailable]);

  // Unlike a full page exit, Next.js client navigation does not emit pagehide.
  // Layout cleanup runs while the audio element is still attached, so its exact
  // currentTime is available for the final keepalive checkpoint.
  useLayoutEffect(
    () => () => {
      if (resumeAvailable) {
        persistAudioPosition(undefined, {
          keepalive: true,
        });
      }
    },
    [persistAudioPosition, resumeAvailable],
  );

  if (statusFailed && !status) {
    return (
      <AudioUnavailable
        note="The studio narration could not be reached. Your saved audio position is unchanged."
        onRetry={retryStudioAudio}
      />
    );
  }
  if (!status) {
    return (
      <div
        className="min-h-[7.75rem] rounded-md border border-neutral-200 bg-neutral-50 p-3"
        aria-busy="true"
        aria-label="Preparing lesson audio"
      >
        <span className="text-xs font-semibold uppercase tracking-wide text-slate-500">
          Listen
        </span>
      </div>
    );
  }
  if (
    !status.narration ||
    status.voices.length === 0
  ) {
    return (
      <AudioUnavailable
        note="The studio narration for this lesson is currently unavailable. Your saved audio position is unchanged."
        onRetry={retryStudioAudio}
      />
    );
  }

  if (mediaRetryExhausted) {
    return (
      <AudioUnavailable
        note="The studio narration could not be played after several attempts. Your saved audio position is unchanged."
        onRetry={retryStudioAudio}
      />
    );
  }

  if (!selected?.ready) {
    return (
      <AudioUnavailable
        note="The studio narration for this lesson is being prepared. Your saved audio position is unchanged."
        onRetry={retryStudioAudio}
      />
    );
  }

  return (
    <div className="space-y-2 rounded-md border border-neutral-200 bg-neutral-50 p-3">
      <audio
        ref={audioRef}
        preload="metadata"
        onLoadedMetadata={onLoadedMetadata}
        onDurationChange={applyPendingSeek}
        onCanPlay={applyPendingSeek}
        onPlaying={() => {
          applyPendingSeek();
          if (
            stopRestartStateRef.current ===
            "restarting"
          ) {
            stopRestartSawPlayingRef.current = true;
          }
          if (
            pendingInitialSeekSecondsRef.current === null
          ) {
            followCueEnabledRef.current = true;
            syncActiveTrackCue();
          }
        }}
        onTimeUpdate={() => {
          const el = audioRef.current;
          if (el && rejectStaleStoppedClock(el)) {
            return;
          }
          const time = el?.currentTime ?? 0;
          if (
            pendingInitialSeekSecondsRef.current !== null &&
            !allowAudioSaveRef.current
          ) {
            setCurrentTime(
              pendingInitialSeekSecondsRef.current,
            );
            return;
          }
          setCurrentTime(time);
          syncActiveTrackCue();
          const now = Date.now();
          if (
            el &&
            now - lastShadowSaveAtRef.current >= 250
          ) {
            lastShadowSaveAtRef.current = now;
            persistAudioShadow(time);
          }
          if (
            el &&
            !el.paused &&
            mediaPlaybackStartedAtRef.current !== null &&
            now - mediaPlaybackStartedAtRef.current >= 5000
          ) {
            mediaRetryAttemptRef.current = 0;
            mediaPlaybackStartedAtRef.current = null;
          }
          if (
            el &&
            !el.paused &&
            now - lastTimedSaveAtRef.current >= 5000
          ) {
            lastTimedSaveAtRef.current = now;
            persistAudioPosition(time);
          }
        }}
        onPlay={() => {
          if (
            stopRestartStateRef.current ===
            "restarting"
          ) {
            // Measure from the media attempt itself, not from the button click:
            // WebKit may defer `play` while it buffers.
            stopRestartStartedAtRef.current =
              window.performance.now();
            stopRestartSawPlayingRef.current = false;
          }
          if (
            pendingInitialSeekSecondsRef.current === null
          ) {
            followCueEnabledRef.current = true;
            syncActiveTrackCue();
          } else if (pendingSectionCueRef.current) {
            followCueEnabledRef.current = true;
            setActiveCue(pendingSectionCueRef.current);
          } else {
            followCueEnabledRef.current = false;
            setActiveCue(null);
          }
          setPlaying(true);
          setFollowAlongPlaying(true);
          mediaPlaybackStartedAtRef.current = Date.now();
        }}
        onPause={() => {
          setPlaying(false);
          setFollowAlongPlaying(false);
          mediaPlaybackStartedAtRef.current = null;
          persistAudioPosition();
        }}
        onSeeked={() => {
          const el = audioRef.current;
          if (
            el &&
            stopRestartStateRef.current ===
              "correcting" &&
            stopRestartPendingZeroRef.current
          ) {
            stopRestartPendingZeroRef.current = false;
            let zeroApplied = false;
            try {
              el.currentTime = 0;
              zeroApplied = true;
            } catch {
              stopRestartPendingZeroRef.current = true;
            }
            setCurrentTime(0);
            persistAudioPosition(0);
            if (zeroApplied) {
              stopRestartStateRef.current =
                "restarting";
              stopRestartStartedAtRef.current =
                window.performance.now();
              stopRestartSawPlayingRef.current = false;
              // The same media element was already authorized by the user's
              // click. Reloading retires WebKit's queued pre-Stop clock before
              // replacing only the aborted stale attempt.
              el.load();
              requestPlayback(el);
            }
            return;
          }
          if (
            el &&
            rejectStaleStoppedClock(el)
          ) {
            persistAudioPosition(0);
            return;
          }
          applyPendingSeek();
          syncActiveTrackCue();
          persistAudioPosition();
        }}
        onError={(event) => {
          // React observes a failed child <track> through the audio subtree.
          // Timed-text failure disables Follow Along only; it must never
          // trigger retries or remove the independently healthy narration.
          if (event.target !== event.currentTarget) {
            selectedSectionPathRef.current = null;
            pendingSectionCueRef.current = null;
            pendingSectionSeekAssignedRef.current = false;
            setActiveCue(null);
            return;
          }
          // Refresh status in case the active release changed. If the same
          // ready asset suffered a transient media/network failure, force a
          // bounded-backoff reload as well: a fresh status object alone does
          // not rerun the browser's media load algorithm.
          const el = audioRef.current;
          selectedSectionPathRef.current = null;
          pendingSectionCueRef.current = null;
          pendingSectionSeekAssignedRef.current = false;
          stopRestartStateRef.current = null;
          stopRestartSawPlayingRef.current = false;
          stopRestartPendingZeroRef.current = false;
          playAttemptGenerationRef.current += 1;
          if (
            el &&
            Number.isFinite(el.currentTime) &&
            el.currentTime > 0
          ) {
            pendingInitialSeekSecondsRef.current =
              el.currentTime;
          }
          setPlaying(false);
          setFollowAlongPlaying(false);
          mediaPlaybackStartedAtRef.current = null;
          void refreshStatus();
          if (mediaRetryTimerRef.current === null) {
            const attempt = mediaRetryAttemptRef.current;
            if (attempt >= MAX_MEDIA_RETRY_ATTEMPTS) {
              persistAudioPosition(undefined, {
                keepalive: true,
              });
              setMediaRetryExhausted(true);
              return;
            }
            mediaRetryAttemptRef.current = attempt + 1;
            const delay = Math.min(
              1000 * 2 ** attempt,
              10_000,
            );
            mediaRetryTimerRef.current =
              window.setTimeout(() => {
                mediaRetryTimerRef.current = null;
                setMediaReload((value) => value + 1);
              }, delay);
          }
        }}
        onEnded={() => {
          const el = audioRef.current;
          selectedSectionPathRef.current = null;
          pendingSectionCueRef.current = null;
          pendingSectionSeekAssignedRef.current = false;
          stopRestartStateRef.current = "stopped";
          stopRestartStartedAtRef.current = 0;
          stopRestartSawPlayingRef.current = false;
          stopRestartPendingZeroRef.current = false;
          playAttemptGenerationRef.current += 1;
          followCueEnabledRef.current = false;
          if (el) {
            try {
              el.currentTime = 0;
            } catch {
              // Persisted and visible state remain authoritatively zero.
            }
          }
          setPlaying(false);
          setFollowAlongPlaying(false);
          setActiveCue(null);
          mediaPlaybackStartedAtRef.current = null;
          setCurrentTime(0);
          persistAudioPosition(0);
        }}
      >
        {followAlong ? (
          <track
            key={followAlong.manifestHash}
            ref={trackRef}
            kind="metadata"
            src={followAlong.trackUrl}
            default
          />
        ) : null}
      </audio>
      <div className="flex flex-wrap items-center gap-3">
        <span className="text-xs font-semibold uppercase tracking-wide text-slate-500">Listen</span>
        <button
          type="button"
          onClick={toggle}
          disabled={resumePending}
          aria-busy={resumePending}
          className="inline-flex h-9 items-center gap-1.5 rounded-md bg-navy-900 px-3 text-sm font-medium text-white hover:bg-navy-700 disabled:cursor-wait disabled:opacity-60"
        >
          {playing ? <Pause className="h-4 w-4" aria-hidden="true" /> : <Play className="h-4 w-4" aria-hidden="true" />}
          {resumePending
            ? "Restoring"
            : playing
            ? "Pause"
            : currentTime >= 1
              ? "Resume"
              : "Play"}
        </button>
        <button
          type="button"
          onClick={stop}
          disabled={resumePending}
          className="inline-flex h-9 items-center gap-1.5 rounded-md border border-neutral-300 bg-white px-3 text-sm font-medium text-navy-900 hover:bg-neutral-50 disabled:cursor-wait disabled:opacity-60"
        >
          <Square className="h-4 w-4" aria-hidden="true" /> Stop
        </button>
        <label className="flex items-center gap-2 text-xs text-slate-600">
          Speed
          <select
            value={rate}
            onChange={(e) => changeRate(Number(e.target.value))}
            className="h-8 rounded-md border border-neutral-300 bg-white px-2 text-sm"
          >
            {RATES.map((r) => (
              <option key={r} value={r}>{r}x</option>
            ))}
          </select>
        </label>
        {!status.productionVoiceLocked &&
        status.voices.filter((voice) => voice.ready).length >
          1 ? (
          <label className="flex items-center gap-2 text-xs text-slate-600">
            Voice
            <select
              value={selected.id}
              onChange={(e) => changeVoice(e.target.value)}
              className="h-8 max-w-[13rem] rounded-md border border-neutral-300 bg-white px-2 text-sm"
            >
              {status.voices.map((v) => (
                <option key={v.id} value={v.id} disabled={!v.ready}>
                  {v.label}
                  {v.ready ? "" : " (unavailable)"}
                </option>
              ))}
            </select>
          </label>
        ) : null}
      </div>
      <div className="flex items-center gap-2">
        <span className="w-10 text-right text-xs tabular-nums text-slate-500">{formatTime(currentTime)}</span>
        <input
          type="range"
          min={0}
          max={Math.max(1, Math.floor(duration))}
          step={1}
          value={Math.min(Math.floor(currentTime), Math.floor(duration))}
          onChange={(e) => seek(Number(e.target.value))}
          disabled={resumePending}
          aria-label="Seek"
          aria-valuetext={`${formatTime(currentTime)} of ${formatTime(duration)}`}
          className="h-1.5 flex-1 cursor-pointer accent-navy-900"
        />
        <span className="w-10 text-xs tabular-nums text-slate-500">{formatTime(duration)}</span>
      </div>
    </div>
  );
}
